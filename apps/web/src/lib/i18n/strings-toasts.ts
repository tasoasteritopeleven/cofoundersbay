const PREFIXES = Object.keys(TOAST_EL).filter((k) => k.endsWith(':'));

/** Greek for a toast string, or undefined when there is none. */
export function toastEl(text: string | undefined): string | undefined {
  if (!text) return undefined;
  const exact = TOAST_EL[text];
  if (exact) return exact;
  const prefix = PREFIXES.find((p) => text.startsWith(p));
  return prefix ? TOAST_EL[prefix] + text.slice(prefix.length) : undefined;
}
