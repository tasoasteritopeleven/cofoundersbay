'use strict';
const crypto = require('node:crypto');

module.exports = async function probes({ base, sql, record, secret }) {
  const password = crypto.randomBytes(24).toString('base64url') + '!9aA';
  function requireFixture(name, value, predicate = x => typeof x === 'string' && x.length > 0) {
    const valid = predicate(value);
    record(name, valid, valid ? 'Required fixture captured' : 'Required fixture missing/invalid; dependent probes stopped');
    if (!valid) throw new Error(name + ' unavailable');
    return value;
  }
  function refreshFixture(name, value) {
    return requireFixture(name, value, x => typeof x === 'string' && /^[a-f0-9]{64}$/.test(x));
  }
  function client() { return { cookies: new Map() }; }
  async function request(who, method, route, body, csrf = true, extraHeaders = {}) {
    const headers = { 'content-type': 'application/json', ...extraHeaders };
    if (who) {
      headers.cookie = [...who.cookies].filter(([k]) => k !== 'cfb_refresh' || route.startsWith('/auth'))
        .map(([k, v]) => `${k}=${v}`).join('; ');
      if (csrf && who.cookies.has('cfb_csrf')) headers['x-csrf-token'] = who.cookies.get('cfb_csrf');
    }
    const response = await fetch(base + route, { method, headers,
      body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(10000) });
    const cookies = response.headers.getSetCookie();
    for (const cookie of cookies) {
      const pair = cookie.split(';')[0], at = pair.indexOf('=');
      if (who) who.cookies.set(pair.slice(0, at), pair.slice(at + 1));
    }
    const text = await response.text();
    let json; try { json = JSON.parse(text); } catch { json = {}; }
    return { status: response.status, data: json.data ?? json, cookies };
  }
  async function check(name, who, method, route, body, expected, csrf = true, headers) {
    const r = await request(who, method, route, body, csrf, headers);
    record(name, expected.includes(r.status), `${method} ${route.replace(/[a-z0-9]{20,}/g, '[fixture-id]')} → ${r.status}; expected ${expected.join('/')}`);
    return r;
  }
  const a = client(), b = client(), c = client();
  const registration = await check('Register founder (real Argon2 and DB)', a, 'POST', '/auth/register',
    { email: 'founder-a@example.invalid', password, role: 'founder' }, [201]);
  const other = await check('Register investor', b, 'POST', '/auth/register',
    { email: 'investor-b@example.invalid', password, role: 'investor' }, [201]);
  const third = await check('Register second founder', c, 'POST', '/auth/register',
    { email: 'founder-c@example.invalid', password, role: 'founder' }, [201]);
  if (!registration.data.user || !other.data.user || !third.data.user) throw new Error('Registration fixture unavailable; dependent probes stopped');
  const aid = registration.data.user.id, bid = other.data.user.id, cid = third.data.user.id;
  // IDs used in SQL are generated by the real database, but still fail closed.
  if (![aid, bid, cid].every(id => /^[a-zA-Z0-9_-]+$/.test(id))) throw new Error('Unexpected fixture ID');
  record('Cookie attributes', registration.cookies.some(x => /^cfb_access=/.test(x) && /HttpOnly/.test(x) && /SameSite=Lax/.test(x)) &&
    registration.cookies.some(x => /^cfb_refresh=/.test(x) && /Path=\/api\/auth/.test(x) && /HttpOnly/.test(x)),
    'HttpOnly access/refresh; SameSite=Lax; refresh path /api/auth (test environment)');
  await check('Cookie-authenticated current user', a, 'GET', '/auth/me', undefined, [200]);
  await check('Anonymous denied', null, 'GET', '/shortlist', undefined, [401]);
  await check('Wrong role denied', a, 'GET', '/admin/users', undefined, [403]);
  await check('Incorrect password denied', null, 'POST', '/auth/login',
    { email: 'founder-a@example.invalid', password: 'Wrong-password!9' }, [401]);
  await check('Missing CSRF denied', a, 'POST', '/shortlist', { userId: bid }, [403], false);
  await check('Mismatched CSRF denied', a, 'POST', '/shortlist', { userId: bid }, [403], false,
    { 'x-csrf-token': 'mismatch' });
  for (const [label, who] of [['Founder', a], ['Other account', b]]) {
    const empty = await check(`${label} empty shortlist HTTP`, who, 'GET', '/shortlist', undefined, [200]);
    record(`${label} empty shortlist shape`, Array.isArray(empty.data.items) &&
      empty.data.items.length === 0 && empty.data.nextCursor === null);
  }
  // Only b has a Profile. c intentionally has none, to exercise nullable projection.
  sql(`INSERT INTO "Profile" (id,"userId","displayName",headline,location,"updatedAt")
    VALUES ('fixture-profile-b','${bid}','Synthetic Investor','Synthetic headline','Athens',NOW());
    INSERT INTO "Skill" (id,name,slug) VALUES
    ('fixture-skill-1','Synthetic Skill One','fixture-skill-one'),
    ('fixture-skill-2','Synthetic Skill Two','fixture-skill-two');
    INSERT INTO "ProfileSkill" ("profileId","skillId") VALUES
    ('fixture-profile-b','fixture-skill-1'),('fixture-profile-b','fixture-skill-2')`);
  await check('Shortlist create', a, 'POST', '/shortlist', { userId: bid, note: 'initial synthetic note' }, [201]);
  await check('Shortlist update', a, 'PATCH', `/shortlist/${bid}/note`, { note: 'persisted synthetic note' }, [200]);
  await check('Second shortlist create', a, 'POST', '/shortlist', { userId: cid }, [201]);
  // Make pagination order deterministic without relying on wall-clock resolution.
  sql(`UPDATE "SavedProfile" SET "createdAt"=NOW()-INTERVAL '1 minute' WHERE "savedById"='${aid}' AND "userId"='${bid}';
    UPDATE "SavedProfile" SET "createdAt"=NOW() WHERE "savedById"='${aid}' AND "userId"='${cid}'`);
  const reloaded = await check('Shortlist HTTP reload', a, 'GET', '/shortlist', undefined, [200]);
  const items = reloaded.data.items;
  const savedB = Array.isArray(items) ? items.find(x => x.userId === bid) : null;
  const savedC = Array.isArray(items) ? items.find(x => x.userId === cid) : null;
  record('Reload contains exactly owner saved entries', Array.isArray(items) &&
    items.length === 2 && items.every(x => x.userId === bid || x.userId === cid) && reloaded.data.nextCursor === null);
  record('Reload contains persisted private note', savedB?.note === 'persisted synthetic note');
  record('Role comes from User and profile skills resolve', savedB?.profile?.role === 'investor' &&
    savedB.profile.displayName === 'Synthetic Investor' && savedB.profile.headline === 'Synthetic headline' &&
    savedB.profile.location === 'Athens' && savedB.profile.avatarUrl === null &&
    Array.isArray(savedB.profile.skills) && savedB.profile.skills.length === 2 &&
    ['Synthetic Skill One', 'Synthetic Skill Two'].every(name => savedB.profile.skills.includes(name)));
  record('Null profile and note serialized', savedC?.profile === null && savedC?.note === null &&
    typeof savedC?.savedAt === 'string' && !Number.isNaN(Date.parse(savedC.savedAt)));
  const first = await check('Shortlist first page HTTP', a, 'GET', '/shortlist?limit=1', undefined, [200]);
  record('First page cursor and contents', first.data.items?.length === 1 &&
    first.data.items[0].userId === cid && typeof first.data.items[0].id === 'string' &&
    first.data.nextCursor === first.data.items[0].id);
  const second = await check('Shortlist cursor page HTTP', a, 'GET',
    `/shortlist?limit=1&cursor=${encodeURIComponent(first.data.nextCursor ?? '')}`, undefined, [200]);
  record('Cursor page has remaining item only', second.data.items?.length === 1 &&
    second.data.items[0].userId === bid && second.data.items[0].note === 'persisted synthetic note' &&
    second.data.nextCursor === null);
  record('Shortlist SQL corroboration', sql(`SELECT count(*) FROM "SavedProfile" WHERE "savedById"='${aid}' AND "userId"='${bid}' AND note='persisted synthetic note'`) === '1' &&
    sql(`SELECT count(*) FROM "SavedProfile" WHERE "savedById"='${aid}' AND "userId"='${cid}' AND note IS NULL`) === '1');
  const privateList = await check('Other account list', b, 'GET', '/shortlist', undefined, [200]);
  record('Other account cannot read private shortlist', Array.isArray(privateList.data.items) &&
    privateList.data.items.length === 0 && privateList.data.nextCursor === null);
  await check('Other account cannot mutate shortlist', b, 'PATCH', `/shortlist/${cid}/note`, { note: 'unauthorized' }, [400, 403, 404]);
  await check('Other account saves its own private note', b, 'POST', '/shortlist',
    { userId: aid, note: 'other account private note' }, [201]);
  const otherOwned = await check('Other account populated shortlist HTTP', b, 'GET', '/shortlist', undefined, [200]);
  record('Other account sees only its own note and null profile', otherOwned.data.items?.length === 1 &&
    otherOwned.data.items[0].userId === aid && otherOwned.data.items[0].note === 'other account private note' &&
    otherOwned.data.items[0].profile === null && otherOwned.data.nextCursor === null &&
    !JSON.stringify(otherOwned.data).includes('persisted synthetic note'));
  const ownerAgain = await check('Owner list after other account save', a, 'GET', '/shortlist', undefined, [200]);
  record('Owner cannot read other account private note', ownerAgain.data.items?.length === 2 &&
    !JSON.stringify(ownerAgain.data).includes('other account private note'));
  const board = await check('Research board create', a, 'POST', '/research/boards', { title: 'Disposable verification board' }, [201]);
  {
    const id = requireFixture('Research board ID', board.data.board?.id,
      x => typeof x === 'string' && /^[a-zA-Z0-9_-]+$/.test(x));
    await check('Cross-resource board read denied', b, 'GET', `/research/boards/${id}`, undefined, [403, 404]);
    await check('Cross-resource board write denied', b, 'PATCH', `/research/boards/${id}`, { title: 'unauthorized' }, [403, 404]);
    await check('Research board update', a, 'PATCH', `/research/boards/${id}`, { title: 'Persisted verification board' }, [200]);
    const read = await check('Research board read', a, 'GET', `/research/boards/${id}`, undefined, [200]);
    record('Research update persists on HTTP read', read.data.board?.title === 'Persisted verification board');
    await check('Research board delete', a, 'DELETE', `/research/boards/${id}`, undefined, [200]);
    await check('Deleted board unavailable', a, 'GET', `/research/boards/${id}`, undefined, [403, 404]);
  }
  // Tenant CRUD itself is globally admin-only. Exercise real tenant memberships
  // and tenant-linked resource memberships rather than mislabeling that guard.
  sql(`INSERT INTO "Tenant" (id,slug,name,"updatedAt") VALUES ('fixture-tenant-a','fixture-tenant-a','Synthetic A',NOW()),('fixture-tenant-b','fixture-tenant-b','Synthetic B',NOW())`);
  sql(`INSERT INTO "TenantMembership" (id,"tenantId","userId",role) VALUES
    ('fixture-membership-a','fixture-tenant-a','${aid}','owner'),
    ('fixture-membership-b','fixture-tenant-b','${bid}','owner');
    INSERT INTO "Organization" (id,"tenantId","createdById",type,name,slug,"updatedAt") VALUES
    ('fixture-org-a','fixture-tenant-a','${aid}','incubator','Synthetic org A','fixture-org-a',NOW()),
    ('fixture-org-b','fixture-tenant-b','${bid}','incubator','Synthetic org B','fixture-org-b',NOW());
    INSERT INTO "OrganizationMembership" (id,"organizationId","userId",role) VALUES
    ('fixture-org-member-a','fixture-org-a','${aid}','owner'),
    ('fixture-org-member-b','fixture-org-b','${bid}','owner')`);
  for (const [who, own, foreign] of [[a, 'a', 'b'], [b, 'b', 'a']]) {
    const memberships = await check(`Tenant ${own} membership scope`, who, 'GET', '/sso/memberships', undefined, [200]);
    record(`Tenant ${own} sees own membership only`, Array.isArray(memberships.data.memberships) &&
      memberships.data.memberships.length === 1 && memberships.data.memberships[0].tenantId === `fixture-tenant-${own}`);
    await check(`Tenant ${own} resource owner positive control`, who, 'PATCH', `/organizations/fixture-org-${own}`,
      { name: `Owner update ${own}` }, [200]);
    await check(`Tenant ${own} cannot edit tenant ${foreign} resource`, who, 'PATCH', `/organizations/fixture-org-${foreign}`,
      { name: 'unauthorized' }, [403]);
    await check(`Tenant ${own} cannot grant foreign resource membership`, who, 'POST', `/organizations/fixture-org-${foreign}/members`,
      { userId: own === 'a' ? aid : bid, role: 'admin' }, [403]);
  }
  record('Cross-tenant resource denial SQL corroboration',
    sql(`SELECT count(*) FROM "Organization" WHERE (id='fixture-org-a' AND name='Owner update a') OR (id='fixture-org-b' AND name='Owner update b')`) === '2' &&
    sql(`SELECT count(*) FROM "OrganizationMembership" WHERE "organizationId" IN ('fixture-org-a','fixture-org-b')`) === '2',
    'Two tenant-linked owner updates persist; denied edits/grants leave names and membership rows unchanged');
  // Downgrade same tenant/resource member: membership alone must not confer admin.
  sql(`UPDATE "OrganizationMembership" SET role='member' WHERE id='fixture-org-member-a'`);
  await check('Downgraded resource member cannot edit own tenant resource', a, 'PATCH', '/organizations/fixture-org-a',
    { name: 'unauthorized after downgrade' }, [403]);
  sql(`UPDATE "OrganizationMembership" SET role='owner' WHERE id='fixture-org-member-a'`);
  await check('Global tenant administration role denial (separate boundary)', a, 'PATCH', '/tenants/fixture-tenant-b', { name: 'unauthorized' }, [403]);
  const old = refreshFixture('Original refresh captured', a.cookies.get('cfb_refresh'));
  const rotated = await check('Refresh rotation', a, 'POST', '/auth/refresh', {}, [201]);
  const newRefresh = refreshFixture('Rotated refresh captured', rotated.data.refreshToken);
  record('Refresh token changes', newRefresh !== old && a.cookies.get('cfb_refresh') === newRefresh);
  await check('Rotated token replay denied', null, 'POST', '/auth/refresh', { refreshToken: old }, [401]);
  const hash = crypto.createHash('sha256').update(newRefresh).digest('hex');
  sql(`UPDATE "RefreshToken" SET "expiresAt"=NOW()-INTERVAL '1 minute' WHERE "tokenHash"='${hash}'`);
  await check('Expired persisted refresh denied', a, 'POST', '/auth/refresh', {}, [401]);
  const expiredBody = Buffer.from(JSON.stringify({ sub: aid, email: 'founder-a@example.invalid', role: 'founder', type: 'access', exp: Math.floor(Date.now() / 1000) - 60 })).toString('base64url');
  const head = Buffer.from(JSON.stringify({ alg: 'HS256', typ: 'JWT' })).toString('base64url');
  const expired = `${head}.${expiredBody}.${crypto.createHmac('sha256', secret).update(`${head}.${expiredBody}`).digest('base64url')}`;
  await check('Correctly signed expired JWT denied', null, 'GET', '/auth/me', undefined, [401], true, { authorization: `Bearer ${expired}` });
  const fresh = client();
  const login = await check('New login after persistence writes', fresh, 'POST', '/auth/login',
    { email: 'founder-a@example.invalid', password }, [201]);
  const logoutRefresh = refreshFixture('Logout refresh captured from successful new login', login.data.tokens?.refreshToken);
  requireFixture('New-login refresh cookie matches body', fresh.cookies.get('cfb_refresh'), value => value === logoutRefresh);
  const logoutHash = crypto.createHash('sha256').update(logoutRefresh).digest('hex');
  record('Pre-logout refresh exists in SQL', sql(`SELECT count(*) FROM "RefreshToken" WHERE "tokenHash"='${logoutHash}'`) === '1');
  const persisted = await check('New login reads shortlist', fresh, 'GET', '/shortlist', undefined, [200]);
  record('New session persistence and projection', persisted.data.items?.length === 2 &&
    persisted.data.items.some(x => x.userId === bid && x.note === 'persisted synthetic note' && x.profile?.role === 'investor') &&
    persisted.data.items.some(x => x.userId === cid && x.profile === null && x.note === null) &&
    !JSON.stringify(persisted.data).includes('other account private note'));
  await check('Shortlist delete', fresh, 'DELETE', `/shortlist/${bid}`, undefined, [200]);
  await check('Second shortlist delete', fresh, 'DELETE', `/shortlist/${cid}`, undefined, [200]);
  record('Delete SQL corroboration', sql(`SELECT count(*) FROM "SavedProfile" WHERE "savedById"='${aid}'`) === '0');
  const afterDelete = await check('Shortlist empty after delete HTTP', fresh, 'GET', '/shortlist', undefined, [200]);
  record('Deleted entries absent on HTTP read', afterDelete.data.items?.length === 0 && afterDelete.data.nextCursor === null);
  const logout = await check('Logout', fresh, 'POST', '/auth/logout', {}, [201]);
  record('Logout clears auth cookie', logout.cookies.some(x => /^cfb_access=;/.test(x)));
  await check('Logged-out cookie session denied', fresh, 'GET', '/auth/me', undefined, [401]);
  record('Logout refresh deleted in SQL', sql(`SELECT count(*) FROM "RefreshToken" WHERE "tokenHash"='${logoutHash}'`) === '0');
  await check('Logged-out refresh revoked', null, 'POST', '/auth/refresh', { refreshToken: logoutRefresh }, [401]);
  record('Synthetic accounts SQL corroboration', sql(`SELECT count(*) FROM "User" WHERE email IN ('founder-a@example.invalid','investor-b@example.invalid','founder-c@example.invalid') AND "passwordHash" LIKE '$argon2id$%'`) === '3');
  return { accounts: [
    { email: 'founder-a@example.invalid', password, userId: aid, tenantId: 'fixture-tenant-a', organizationId: 'fixture-org-a' },
    { email: 'investor-b@example.invalid', password, userId: bid, tenantId: 'fixture-tenant-b', organizationId: 'fixture-org-b' },
  ], instructions: 'Use real /api/auth/login; no demo cookies or preview mode. Shortlist/board CRUD fixtures were deleted by tests. Tenant-linked organization fixtures remain until cleanup.' };
};